const ITEM_MAP = new Map<number, ItemDefinition>();
for (const def of ITEM_REGISTRY_LIST) {
  ITEM_MAP.set(def.id, def);
}

export function getItemDef(id: number): ItemDefinition {
  return ITEM_MAP.get(id) ?? ITEM_REGISTRY_LIST[0]!;
}

export function isSolidBlock(blockId: number): boolean {
  const def = ITEM_MAP.get(blockId);
  return Boolean(def?.isBlock && def.solid);
}

export function isCollidableBlock(blockId: number): boolean {
  const def = ITEM_MAP.get(blockId);
  return Boolean(def?.isBlock && def.collidable);
}

export function isOpaqueCube(blockId: number): boolean {
  const def = ITEM_MAP.get(blockId);
  return Boolean(def?.isBlock && def.solid && !def.transparent && (def.shape ?? 'CUBE') === 'CUBE');
}

export function calculateBlockBreakDuration(
  blockId: number,
  heldItemId: number | null,
  isCreative: boolean
): number {
  if (isCreative) return 0.05;
  const block = getItemDef(blockId);
  if (!block.isBlock || block.breakTime === undefined) return 0.5;
  if (block.breakTime >= 999) return 999999;

  const held = heldItemId ? getItemDef(heldItemId) : null;
  const heldToolType: ToolType = held?.toolType ?? 'NONE';
  const heldTier: ToolTier = held?.toolTier ?? 0;

  if (block.minToolTier && block.minToolTier > 0) {
    if (heldToolType !== block.preferredTool || heldTier < block.minToolTier) {
      return block.breakTime * 3.2;
    }
  }

  if (block.preferredTool && heldToolType === block.preferredTool) {
    const speedMult = held?.miningSpeedMultiplier ?? 2.0;
    return Math.max(0.08, block.breakTime / speedMult);
  }

  return block.breakTime;
}

/**
 * Checks whether breaking `blockId` with `heldItemId` meets the block's tool & tier requirement
 * to harvest its resource drop. Blocks with `minToolTier > 0` require the matching tool type
 * and a `toolTier >= minToolTier`.
 */
export function canHarvestBlockDrop(
  blockId: number,
  heldItemId: number | null
): boolean {
  const block = getItemDef(blockId);
  if (!block.isBlock || blockId === BLOCK_IDS.AIR || blockId === BLOCK_IDS.BEDROCK) {
    return false;
  }
  if (!block.minToolTier || block.minToolTier <= 0) {
    return true;
  }
  const held = heldItemId ? getItemDef(heldItemId) : null;
  const heldToolType: ToolType = held?.toolType ?? 'NONE';
  const heldTier: ToolTier = held?.toolTier ?? 0;

  if (block.preferredTool && heldToolType !== block.preferredTool) {
    return false;
  }
  return heldTier >= block.minToolTier;
}

/**
 * Computes the item drops yielded when breaking `blockId` with `heldItemId`.
 * Respects tool tier requirements and provides natural foliage drops (sticks/apples/berries).
 */
export function getBlockDrops(
  blockId: number,
  heldItemId: number | null,
  rand = Math.random()
): Array<{ itemId: number; count: number }> {
  if (!canHarvestBlockDrop(blockId, heldItemId)) {
    return [];
  }

  // Leaves can drop sticks + fruit naturally for survival progression
  if (blockId === BLOCK_IDS.OAK_LEAVES) {
    if (rand < 0.35) return [{ itemId: ITEM_IDS.ORCHARD_APPLE, count: 1 }];
    if (rand < 0.75) return [{ itemId: ITEM_IDS.STICK, count: 1 }];
    return [{ itemId: ITEM_IDS.ORCHARD_APPLE, count: 1 }];
  }
  if (blockId === BLOCK_IDS.BIRCH_LEAVES) {
    if (rand < 0.65) return [{ itemId: ITEM_IDS.STICK, count: 1 }];
    return [{ itemId: ITEM_IDS.ORCHARD_APPLE, count: 1 }];
  }
  if (blockId === BLOCK_IDS.PINE_LEAVES) {
    if (rand < 0.55) return [{ itemId: ITEM_IDS.WILD_BERRY, count: 1 }];
    return [{ itemId: ITEM_IDS.STICK, count: 1 }];
  }

  const block = getItemDef(blockId);
  const dropId = block.dropItemId ?? blockId;
  const dropCount = block.dropCount ?? 1;
  if (dropId <= 0 || dropCount <= 0) return [];
  return [{ itemId: dropId, count: dropCount }];
}
